-- Data/PlayerData.lua
-- Player data (raid progression, rankings, parses) for the player tooltip (UI/ProgressionTooltip.lua).
--
-- This placeholder ships EMPTY. The Logs Uploader desktop app overwrites this
-- file with the realm's progression snapshot when "In-game progression" is on,
-- and the game picks the new contents up on the next /reload or login.
--
-- The file has to exist in the release (and be listed in the .toc) because
-- WoW reads the .toc file list once, at client start: a file the Uploader
-- created later would not load until the whole client restarted, while new
-- CONTENTS of a listed file only need a /reload.
--
-- Do not edit by hand - the Uploader replaces it.
